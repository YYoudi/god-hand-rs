"""Validate the dashboard and derive the public roadmap from one source of truth."""
import argparse
import datetime
import json
from html import escape
from pathlib import Path
from comparisons import validate_comparisons

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / 'docs/dashboard'
LABELS = {'done': 'Done', 'in_progress': 'In progress', 'planned': 'Planned', 'blocked': 'Blocked', 'paused': 'Paused'}


def render(data):
    datetime.date.fromisoformat(data['updated'])
    ids = set()
    milestones = {m['id'] for m in data['milestones']}
    lines = ['# Roadmap — faithful PC port and remaster research', '',
             '<!-- Generated by scripts/dashboard.py from docs/dashboard/data.json. -->', '',
             f"Updated: {data['updated']}. **LasVola PC continuation active; independent engine paused, not achieved.**", '',
             'Each task is a verifiable deliverable, not an estimate of game coverage.',
             'Done applies only to the stated criteria. No release schedule is promised.', '',
             f"Next useful evidence: {data['next']}", '']
    for milestone in data['milestones']:
        assert all(dep in milestones for dep in milestone['depends_on']), 'Unknown milestone dependency'
        lines += [f"## {milestone['id']} — {milestone['title']}", '', milestone['goal'], '',
                  'Dependencies: ' + (', '.join(milestone['depends_on']) or 'none') + '.', '',
                  '| ID | Feature | Status | Acceptance criteria |',
                  '| --- | --- | --- | --- |']
        for task in milestone['tasks']:
            assert task['id'] not in ids, 'Duplicate task ID'
            ids.add(task['id'])
            assert task['status'] in LABELS, 'Invalid task status'
            assert task['acceptance'].strip(), 'Missing acceptance criteria'
            cells = [task['id'], task['title'], LABELS[task['status']], task['acceptance']]
            lines.append('| ' + ' | '.join(c.replace('|', '\\|') for c in cells) + ' |')
        lines.append('')
    for capture in data['captures']:
        assert capture['kind'] == 'dashboard', 'Only dashboard screenshots are public at this stage'
        assert capture['source'] and capture['caption']
        datetime.date.fromisoformat(capture['date'])
        path = (SITE / capture['path']).resolve()
        assert path.is_relative_to((SITE / 'captures').resolve()), 'Capture must stay inside captures/'
        assert path.is_file(), f'Missing capture: {path}'
    validate_comparisons(data.get('comparisons', []), lambda path: (ROOT / path).read_bytes())
    for pair in data.get('comparisons', []):
        assert pair['feature'] in ids, 'Comparison feature must identify a roadmap task'
    for update in data['updates']:
        datetime.date.fromisoformat(update['date'])
        assert update['changes'] and update['validation'] and update['limits']
        if 'link' in update:
            assert update['link']['url'].startswith(data['repo'] + '/blob/main/'), 'Post link must target repository documentation'
    for name in ('style.css',):
        assert (SITE / name).is_file(), f'Missing dashboard asset {name}'
    lines += ['## Outside the public repository', '',
              'Discs, BIOS files, extracted data, translated game code, dumps and unselected captures stay local.',
              'Selected rendered reference/Bevy screenshots may be published under the [comparison protocol](docs/progress-tracking.md).',
              'See [the independent method](docs/clean-room.md) and [notices](NOTICE.md).', '']
    return '\n'.join(lines)


def blog(data):
    posts = []
    for update in data['updates']:
        changes = ''.join('<li>' + escape(change) + '</li>' for change in update['changes'])
        link = update.get('link')
        post_link = (f'<p class="reading"><a href="{escape(link["url"], quote=True)}">{escape(link["label"])}</a></p>' if link else '')
        posts.append(f'''<article>
  <time datetime="{escape(update['date'])}">{escape(update['date'])}</time>
  <h2>{escape(update['title'])}</h2>
  <p>{escape(update['summary'])}</p>
  <ul>{changes}</ul>
{post_link}
  <details><summary>Checks and limitations</summary>
    <p>{escape(update['validation'])}</p><p>{escape(update['limits'])}</p>
  </details>
</article>''')
    captures = ''.join(
        f'<li><a href="{escape(c["path"], quote=True)}">{escape(c["caption"])}</a>'
        f' <small>— {escape(c["date"])} · {escape(c["source"])}</small></li>'
        for c in data['captures'])
    capture_section = f'<section><h2>Journal captures</h2><ul>{captures}</ul></section>' if captures else ''
    pairs = []
    for pair in data.get('comparisons', []):
        figures = []
        for side, label in [('reference', 'Reference'), ('bevy', 'Bevy')]:
            label = escape(pair.get('labels', {}).get(side, label))
            item = pair[side]
            path = escape(item['path'], quote=True)
            caption = escape(item['caption'])
            original = item.get('original')
            download = (f'<a href="{escape(original["path"], quote=True)}" download>Download unchanged original PPM ({item["width"]} × {item["height"]})</a><br>PNG above is a lossless viewing preview.' if original else
                        f'<a href="{path}" download>Download unchanged original ({item["width"]} × {item["height"]})</a>')
            figures.append(f'''<figure><figcaption><strong>{label}</strong> — {caption}</figcaption>
<a href="{path}"><img src="{path}" width="{item['width']}" height="{item['height']}" loading="lazy" alt="{label}: {caption}"></a>
<small>{escape(item['profile'])} · {escape(item['runtime'])}<br>
Captured {escape(item['captured_at'])} · revision {escape(item['revision'])}<br>
{download}</small></figure>''')
        observations = ''.join('<li>' + escape(s) + '</li>' for s in pair['observations'])
        limits = ''.join('<li>' + escape(s) + '</li>' for s in pair['limits'])
        pairs.append(f'''<article id="comparison-{escape(pair['id'], quote=True)}">
<time datetime="{pair['date']}">{pair['date']}</time><h2>{escape(pair['title'])}</h2>
<p>{escape(pair['scenario'])}</p><p><small>Alignment: {escape(pair['alignment'])}; feature {escape(pair['feature'])}. Not a claim of complete fidelity.</small></p>
<div class="comparison">{''.join(figures)}</div><ul>{observations}</ul>
<details><summary>Limits and provenance</summary><ul>{limits}</ul>
<p>Game imagery belongs to its rights holders and is not covered by the project MIT license. Original file hashes are recorded in the public manifest.</p></details></article>''')
    comparison_section = ('<section id="comparisons" aria-label="Reviewed renderer comparisons"><h2>Comparisons</h2>' + ''.join(pairs) + '</section>') if pairs else ''
    return f'''<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="Factual development notes on a faithful God Hand PC port and remaster research.">
  <title>God Hand PC — development journal</title>
  <link rel="stylesheet" href="style.css">
</head>
<body>
<header>
  <a class="site-name" href="./">God Hand PC</a>
  <nav aria-label="Navigation"><a href="#journal">Journal</a><a href="{escape(data['repo'])}/blob/main/ROADMAP.md">Roadmap</a><a href="{escape(data['repo'])}">Code</a></nav>
</header>
<main>
  <section class="about">
    <h1>Development journal</h1>
    <p>The aim is a faithful PC port of God Hand that can later be remastered.
    The active work continues the evaluated LasVola base in the separate GPL
    <a href="https://github.com/YYoudi/god-hand-pc">god-hand-pc project</a>, with a
    personal ISO. Original behavior comes first; PC enhancements are separate
    and reversible, not reasons to rewrite the entire game in another engine.</p>
    <p>The independent Rust/Bevy work is paused and preserved, not complete.
    Third-party runtime results are labeled separately. This page records actual
    checks, original comparisons and what is still unknown.</p>
  </section>
{comparison_section}
  <section id="journal" aria-label="Journal entries">
    {''.join(posts)}
  </section>
  {capture_section}
  <section class="reading">
    <h2>Project background</h2>
    <p><a href="{escape(data['repo'])}/blob/main/docs/research-2026-11-03.md">PS2 recompilation research notes</a><br>
    <a href="{escape(data['repo'])}/blob/main/docs/clean-room.md">Independent implementation method</a><br>
    <a href="{escape(data['repo'])}/blob/main/ROADMAP.md">Planned features</a></p>
  </section>
</main>
<footer>Independent project, unaffiliated with the rights holders.<br>
Preserved lab: MIT · Separate PC continuation: GPL · Game imagery is not project-licensed.<br>
Hosted on free GitHub Pages.</footer>
</body>
</html>
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = json.loads((SITE / 'data.json').read_text(encoding='utf-8'))
    content = render(data)
    outputs = {ROOT / 'ROADMAP.md': content, SITE / 'index.html': blog(data)}
    if args.check:
        for destination, expected in outputs.items():
            assert destination.read_text(encoding='utf-8') == expected, f'{destination.name} stale: run python scripts/dashboard.py'
        print('Blog data, captures, HTML and roadmap: valid.')
    else:
        for destination, expected in outputs.items():
            destination.write_text(expected, encoding='utf-8', newline='\n')
        print('ROADMAP.md and blog HTML updated.')


if __name__ == '__main__':
    main()
